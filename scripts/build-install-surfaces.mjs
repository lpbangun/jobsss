#!/usr/bin/env node
/**
 * Generate the host install surfaces from compat/install-pins.json.
 *
 * Why this exists: the family is one reviewed trio of pinned products, but every
 * host installs plugins its own way (Hermes consumes a plugin pack today; later
 * hosts follow). A surface is distribution metadata that references the canonical
 * product packages at exact commits — never a second source of truth, never a
 * runtime dependency, never a copy of product bytes. Generating every surface
 * from one pins file is what keeps N install channels from becoming N truths.
 *
 * Usage:
 *   node scripts/build-install-surfaces.mjs           # rewrite the generated surfaces
 *   node scripts/build-install-surfaces.mjs --check   # report drift, write nothing (exit 1)
 *   node scripts/build-install-surfaces.mjs --refresh # advance pins to each repo's default-branch head, then rewrite
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const PINS_REL = 'compat/install-pins.json';
export const HERMES_SURFACE_REL = 'compat/hermes/find-people.pack.yaml';

/** Installers accept only exact 40-character commits; tags and branches are rejected. */
const REF_RE = /^[0-9a-f]{40}$/;
const REPO_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*\/[A-Za-z0-9][A-Za-z0-9._-]*$/;
const NAME_RE = /^[a-z0-9][a-z0-9-]*$/;

/** Parse and validate the pins file. Throws on anything an installer would reject later. */
export function readPins(root = REPO_ROOT) {
  const abs = path.join(root, PINS_REL);
  const pins = JSON.parse(fs.readFileSync(abs, 'utf8'));
  if (pins.schemaVersion !== 1) throw new Error(`unsupported pins schemaVersion: ${pins.schemaVersion}`);
  const stack = pins.stack || {};
  if (!NAME_RE.test(String(stack.name || ''))) throw new Error(`invalid stack name: ${stack.name}`);
  if (typeof stack.description !== 'string' || !stack.description.trim()) {
    throw new Error('stack.description is required');
  }
  if (typeof pins.surfaceVersion !== 'string' || !pins.surfaceVersion.trim()) {
    throw new Error('surfaceVersion is required');
  }
  if (!Array.isArray(pins.products) || pins.products.length === 0) {
    throw new Error('pins must declare a non-empty products list');
  }
  const seen = new Set();
  for (const product of pins.products) {
    const label = product && product.name ? product.name : '(unnamed)';
    if (!NAME_RE.test(String(product.name || ''))) throw new Error(`product ${label} has an invalid name`);
    if (seen.has(product.name)) throw new Error(`product ${product.name} is listed twice`);
    seen.add(product.name);
    if (!REPO_RE.test(String(product.repo || ''))) throw new Error(`product ${label} needs an owner/repo source`);
    if (!REF_RE.test(String(product.ref || ''))) {
      throw new Error(
        `product ${label} ref ${product.ref}: refs must be exact 40-character commits ` +
        '(tags and branch names are rejected by installers)');
    }
    if (product.subdir !== undefined && !/^[A-Za-z0-9._/-]+$/.test(String(product.subdir))) {
      throw new Error(`product ${label} has an invalid subdir`);
    }
  }
  return pins;
}

/** Deterministic word wrap for a YAML folded block scalar. */
function foldText(text, width) {
  const words = String(text).trim().split(/\s+/);
  const lines = [];
  let line = '';
  for (const word of words) {
    if (!line) line = word;
    else if (`${line} ${word}`.length <= width) line = `${line} ${word}`;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  return lines;
}

/** Render the Hermes plugin pack for the pinned trio. */
export function renderHermesPack(pins) {
  const lines = [
    '# Generated by scripts/build-install-surfaces.mjs from compat/install-pins.json.',
    '# Do not edit by hand: run `node scripts/build-install-surfaces.mjs` and commit the result.',
    `name: ${pins.stack.name}`,
    'description: >-',
    ...foldText(pins.stack.description, 74).map(line => `  ${line}`),
    `version: "${pins.surfaceVersion}"`,
    'plugins:'
  ];
  for (const product of pins.products) {
    lines.push(`  - repo: ${product.repo}`);
    if (product.subdir) lines.push(`    subdir: ${product.subdir}`);
    lines.push(`    ref: "${product.ref}"`);
  }
  return `${lines.join('\n')}\n`;
}

/** Map of surface path -> rendered text. Add later hosts here as their surfaces land. */
export function renderSurfaces(pins) {
  return new Map([[HERMES_SURFACE_REL, renderHermesPack(pins)]]);
}

/** Compare every rendered surface against the committed one. */
export function surfacesDrift(root = REPO_ROOT) {
  const pins = readPins(root);
  const expected = renderSurfaces(pins);
  const changed = [];
  for (const [rel, text] of expected) {
    const abs = path.join(root, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (current !== text) changed.push(rel);
  }
  return { ok: changed.length === 0, changed, expected };
}

/** Rewrite every surface from the pins. Returns the relative paths written. */
export function writeSurfaces(root = REPO_ROOT) {
  const pins = readPins(root);
  const expected = renderSurfaces(pins);
  const written = [];
  for (const [rel, text] of expected) {
    const abs = path.join(root, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, text);
    written.push(rel);
  }
  return written;
}

/**
 * Advance each pin to its repository's default-branch head. Deliberate, never
 * automatic: the trio moves only when a human asks for it and re-verifies after.
 */
export function refreshPins(root = REPO_ROOT) {
  const abs = path.join(root, PINS_REL);
  const pins = JSON.parse(fs.readFileSync(abs, 'utf8'));
  const changes = [];
  for (const product of pins.products) {
    const out = execFileSync(
      'git',
      ['ls-remote', `https://github.com/${product.repo}.git`, 'HEAD'],
      { encoding: 'utf8', timeout: 60_000 }
    );
    const sha = String(out).trim().split(/\s+/)[0].toLowerCase();
    if (!REF_RE.test(sha)) throw new Error(`could not resolve a default-branch commit for ${product.repo}`);
    if (sha !== product.ref) {
      changes.push({ name: product.name, from: product.ref, to: sha });
      product.ref = sha;
    }
  }
  if (changes.length) fs.writeFileSync(abs, `${JSON.stringify(pins, null, 2)}\n`);
  return changes;
}

function main() {
  const argv = process.argv.slice(2);
  if (argv.includes('--refresh')) {
    const changes = refreshPins();
    if (changes.length === 0) {
      console.log('pins: every product already sits at its default-branch head');
      return;
    }
    for (const change of changes) {
      console.log(`pins: ${change.name} ${change.from.slice(0, 12)} -> ${change.to.slice(0, 12)}`);
    }
    const written = writeSurfaces();
    console.log(`pins: refreshed; rewrote ${written.join(', ')} — rerun the acceptance checks before committing.`);
    return;
  }
  if (argv.includes('--check')) {
    const drift = surfacesDrift();
    if (drift.ok) {
      console.log(`surfaces: ${[...drift.expected.keys()].join(', ')} match ${PINS_REL}`);
      return;
    }
    console.error(`surfaces: drift from ${PINS_REL}`);
    for (const rel of drift.changed) console.error(`  changed or missing: ${rel}`);
    process.exitCode = 1;
    return;
  }
  const written = writeSurfaces();
  console.log(`surfaces: wrote ${written.join(', ')}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
